std::optional<EntityDimensions> javaEntityDimensions(std::string_view path) {
    const auto found = std::ranges::lower_bound(kDimensions, path, {}, &Row::path);
    if (found == kDimensions.end() || found->path != path)
        return std::nullopt;
    return EntityDimensions{found->width, found->height};
}

