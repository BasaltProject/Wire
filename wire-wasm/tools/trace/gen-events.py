#!/usr/bin/env python3
"""Writes src/HostEventsTable.inc and src/HostPlayerProps.inc from the server's own definitions.

Usage: gen-events.py <server>/server-plugins [--check]

Reads PluginEventTypes.cpp (one `PluginEventType type{name, cancellable, {fields}, {mutable}}` per accessor) and
PluginHookEvents.def (one HOOK_EVENT per row), so the trace host lists exactly the events the server declares, and
PluginPlayerOps.hpp for the player property and operation tables.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "src" / "HostEventsTable.inc"
PLAYER_OUT = Path(__file__).resolve().parent / "src" / "HostPlayerProps.inc"
OPS_OUT = Path(__file__).resolve().parent / "src" / "HostPlayerOps.inc"


def strings(text):
    return re.findall(r'"((?:[^"\\]|\\.)*)"', text)


def balanced(text, start):
    """The text between the bracket at `start` and its match, and the index after the match."""
    pairs = {"{": "}", "(": ")"}
    opener = text[start]
    closer = pairs[opener]
    depth = 0
    in_string = False
    for i in range(start, len(text)):
        c = text[i]
        if c == '"' and text[i - 1] != "\\":
            in_string = not in_string
        elif not in_string:
            if c == opener:
                depth += 1
            elif c == closer:
                depth -= 1
                if depth == 0:
                    return text[start + 1:i], i + 1
    raise SystemExit("unbalanced bracket")


def split_top(text):
    """Splits on commas that are not inside brackets or strings."""
    parts, depth, in_string, current = [], 0, False, ""
    for i, c in enumerate(text):
        if c == '"' and (i == 0 or text[i - 1] != "\\"):
            in_string = not in_string
        if not in_string:
            if c in "{(":
                depth += 1
            elif c in "})":
                depth -= 1
            elif c == "," and depth == 0:
                parts.append(current.strip())
                current = ""
                continue
        current += c
    if current.strip():
        parts.append(current.strip())
    return parts


def accessor_events(source):
    rows = []
    for match in re.finditer(r"PluginEventType type\{", source):
        body, _ = balanced(source, match.end() - 1)
        parts = split_top(body)
        name = strings(parts[0])[0]
        cancellable = parts[1] == "true"
        fields = strings(parts[2])
        mutables = strings(parts[3]) if len(parts) > 3 else []
        rows.append((name, cancellable, fields, mutables))
    return rows


def hook_events(source):
    rows = []
    for match in re.finditer(r"HOOK_EVENT\(", source):
        body, _ = balanced(source, match.end() - 1)
        parts = split_top(body)
        name = strings(parts[1])[0]
        cancellable = parts[2] == "true"
        fields = strings(parts[3])
        mutables = strings(parts[4])
        rows.append((name, cancellable, fields, mutables))
    return rows


def render(rows):
    out = ["// Generated by gen-events.py from the server event definitions. Do not edit.\n"]
    for name, cancellable, fields, mutables in sorted(rows):
        out.append('{"%s", %s, "%s", "%s"},\n' % (name, "true" if cancellable else "false", ",".join(fields),
                                                    ",".join(mutables)))
    return "".join(out)


def player_table(source):
    out = ["// Generated by gen-events.py from the server player tables. Do not edit.\n"]
    for name, kind, writable in re.findall(r'EntityPropertySpec\{"(\w+)", EntityValueKind::(\w+), (true|false)\}',
                                           source):
        out.append('{"%s", PlayerKind::%s, %s},\n' % (name, kind, writable))
    return "".join(out)


def ops_table(source):
    out = ["// Generated by gen-events.py from the server player tables. Do not edit.\n"]
    for name in re.findall(r'EntityOperationSpec\{"(\w+)"', source):
        out.append('"%s",\n' % name)
    return "".join(out)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        raise SystemExit(__doc__)
    root = Path(args[0])
    rows = accessor_events((root / "src" / "PluginEventTypes.cpp").read_text())
    rows += hook_events((root / "include/basalt/server/plugins/PluginHookEvents.def").read_text())
    names = [r[0] for r in rows]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate event names")
    text = render(rows)
    ops_source = (root / "include/basalt/server/plugins/PluginPlayerOps.hpp").read_text()
    players = player_table(ops_source)
    operations = ops_table(ops_source)
    if "--check" in sys.argv:
        if OUT.read_text() != text or PLAYER_OUT.read_text() != players or OPS_OUT.read_text() != operations:
            raise SystemExit("a generated table is out of date")
        return
    OUT.write_text(text)
    PLAYER_OUT.write_text(players)
    OPS_OUT.write_text(operations)
    print(len(rows), "events")


main()
