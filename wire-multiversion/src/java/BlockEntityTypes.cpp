std::string_view nativeName(std::int32_t nativeId) {
    if (nativeId < 0 || static_cast<std::size_t>(nativeId) >= kNative.size()) {
        return {};
    }
    return kNative[static_cast<std::size_t>(nativeId)];
}

std::int32_t idAt(std::int32_t protocol, std::int32_t nativeId) {
    const std::string_view name = nativeName(nativeId);
    if (name.empty()) {
        return kNone;
    }
    for (const Era& era : kEras) {
        if (protocol < era.from) {
            continue;
        }
        for (std::size_t index = 0; index < era.names.size(); ++index) {
            if (era.names[index] == name) {
                return static_cast<std::int32_t>(index);
            }
        }
        return kNone;
    }
    return kNone;
}

