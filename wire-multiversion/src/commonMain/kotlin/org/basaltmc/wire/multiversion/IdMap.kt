package org.basaltmc.wire.multiversion

/** One numbering seen from another, whether it is a single step or a whole chain of them. */
public interface IdLookup {
    /** The id the other side uses, or [IdMap.NONE] when it has nothing to show. */
    public fun map(id: Int): Int

    public fun unmap(id: Int): Int
}

/**
 * What one version's numbering for a registry becomes in the version below.
 *
 * Ids barely ever move one at a time: a release inserts a handful of names and everything after
 * each insertion slides by the same amount. So this is stored as runs of constant difference plus
 * the leftovers, which turns a table of thirty thousand block states into fifty five runs.
 *
 * The text it is built from is generated by `tools/protocol-diff`: `start:length:delta` runs, then
 * a pipe, then `native>old` for whatever has no counterpart and is being shown as something else.
 * It is parsed on first use, so a link nobody's client needs costs nothing.
 */
public class IdMap(
    private val encoded: String,
) : IdLookup {
    private var starts: IntArray = EMPTY
    private var lengths: IntArray = EMPTY
    private var deltas: IntArray = EMPTY
    private var substituteFrom: IntArray = EMPTY
    private var substituteTo: IntArray = EMPTY
    private var parsed = false

    /** The id an older client should be sent, or [NONE] when there is nothing to show it. */
    override fun map(id: Int): Int {
        if (!parsed) parse()
        var low = 0
        var high = starts.size - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            val start = starts[mid]
            when {
                id < start -> high = mid - 1
                id >= start + lengths[mid] -> low = mid + 1
                else -> return id + deltas[mid]
            }
        }
        val substitute = substituteFrom.binarySearch(id)
        return if (substitute >= 0) substituteTo[substitute] else NONE
    }

    /** The same lookup backwards, for an id coming from an older client. */
    override fun unmap(id: Int): Int {
        if (!parsed) parse()
        for (i in starts.indices) {
            val from = starts[i] + deltas[i]
            if (id >= from && id < from + lengths[i]) return id - deltas[i]
        }
        return NONE
    }

    private fun parse() {
        val pipe = encoded.indexOf('|')
        val runs = if (pipe < 0) encoded else encoded.substring(0, pipe)
        val tail = if (pipe < 0) "" else encoded.substring(pipe + 1)
        val parts = if (runs.isEmpty()) emptyList() else runs.split(';')
        starts = IntArray(parts.size)
        lengths = IntArray(parts.size)
        deltas = IntArray(parts.size)
        for ((index, part) in parts.withIndex()) {
            val first = part.indexOf(':')
            val second = part.indexOf(':', first + 1)
            starts[index] = part.substring(0, first).toInt()
            lengths[index] = part.substring(first + 1, second).toInt()
            deltas[index] = part.substring(second + 1).toInt()
        }
        val holes = if (tail.isEmpty()) emptyList() else tail.split(';')
        substituteFrom = IntArray(holes.size)
        substituteTo = IntArray(holes.size)
        for ((index, hole) in holes.withIndex()) {
            val arrow = hole.indexOf('>')
            substituteFrom[index] = hole.substring(0, arrow).toInt()
            substituteTo[index] = hole.substring(arrow + 1).toInt()
        }
        parsed = true
    }

    private fun IntArray.binarySearch(value: Int): Int {
        var low = 0
        var high = size - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            when {
                this[mid] < value -> low = mid + 1
                this[mid] > value -> high = mid - 1
                else -> return mid
            }
        }
        return -1
    }

    public companion object {
        /** No id at all on the other side, and no substitute either. */
        public const val NONE: Int = -1

        private val EMPTY = IntArray(0)

        /** A map that changes nothing, for a registry a release left alone. */
        public val IDENTITY: IdMap = IdMap("0:2147483647:0|")
    }
}
